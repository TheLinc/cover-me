// One-off converter: Recraft vector SVG → components/landing/scene-paths.tsx
//
//   node scripts/svg-to-scene.mjs <recraft.svg>   (strip its <metadata> block first)
//
// Source: Higgsfield Recraft V4.1 (vector), job f98289d0-0a20-4cc9-9059-e29f53672b39.
// Maps fills to brand tokens, drops the background and the red thread shapes
// (the thread is re-drawn as a stroked path in the component so it can animate),
// and splits the rest into the left (suit) and right (dress) forms. HeroScene sets the viewBox.
import { readFileSync, writeFileSync } from 'node:fs'
import assert from 'node:assert/strict'

const src = readFileSync(process.argv[2], 'utf8')
const FILL = {
  '28,26,23': 'fill-ink',
  '84,58,15': 'fill-ink',
  '107,102,97': 'fill-ink-2',
  '179,164,137': 'fill-line',
  '230,180,34': 'fill-tape',
  '242,234,219': 'fill-tissue',
  '59,91,143': 'fill-line', // the left head; the right head is recolored below
}
const SPLIT_X = 1070 // between the two forms, in source viewBox units

const paths = [...src.matchAll(/<path[^>]*fill="rgb\(([\d,]+)\)"[^>]*d="([^"]+)"/g)].map(([, rgb, d]) => {
  const cmds = new Set(d.match(/[A-Za-z]/g))
  assert([...cmds].every((c) => 'MLCQZz'.includes(c)), `unsupported path commands: ${[...cmds]}`)
  const n = d.match(/-?\d+(\.\d+)?/g).map(Number)
  const xs = n.filter((_, i) => i % 2 === 0), ys = n.filter((_, i) => i % 2 === 1)
  const box = { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) }
  return { rgb, d: d.replace(/-?\d+\.\d+/g, (v) => (+v).toFixed(1)), box }
})

const isBackground = (p) => p.box.x1 - p.box.x0 > 2000 && p.box.y1 - p.box.y0 > 1100
const kept = paths.filter((p) => !isBackground(p) && p.rgb !== '196,50,31')
assert.equal(paths.length - kept.length, 4, 'expected to drop 1 background + 3 thread shapes')

// The right head is a small solid ink shape near the top of the right form.
for (const p of kept) {
  const w = p.box.x1 - p.box.x0, h = p.box.y1 - p.box.y0
  if (p.rgb === '28,26,23' && p.box.x0 > SPLIT_X && p.box.y1 < 300 && w > 60 && h > 80) p.head = true
}
assert.equal(kept.filter((p) => p.head).length, 1, 'expected exactly one right head')

const cls = (p) => (p.head ? 'fill-line' : FILL[p.rgb])
for (const p of kept) assert(cls(p), `unmapped fill rgb(${p.rgb})`)

const left = kept.filter((p) => (p.box.x0 + p.box.x1) / 2 < SPLIT_X)
const right = kept.filter((p) => (p.box.x0 + p.box.x1) / 2 >= SPLIT_X)
assert(left.length > 20 && right.length > 20, `lopsided split: ${left.length}/${right.length}`)

const group = (ps) => ps.map((p) => `    <path className="${cls(p)}" d="${p.d}" />`).join('\n')
const out = `// Generated by scripts/svg-to-scene.mjs from a Recraft V4.1 vector (Higgsfield job
// f98289d0-0a20-4cc9-9059-e29f53672b39). Edit the script, not this file.
export function SuitForm() {
  return (
    <g className="hero-form">
${group(left)}
    </g>
  )
}

export function DressForm() {
  return (
    <g className="hero-form hero-form--right">
${group(right)}
    </g>
  )
}
`
writeFileSync('components/landing/scene-paths.tsx', out)
console.log(`scene: ${left.length} + ${right.length} paths, ${(out.length / 1024).toFixed(1)} KB`)
